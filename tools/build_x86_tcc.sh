#!/bin/bash
# Cross-build the Tiny C Compiler (tcc) as a native Extron compiler: tcc runs ON Extron,
# compiles for Extron (x86-64, mlibc, dynamic linking via /lib/ld.so). Output:
#     build-x86_64/tcc/rootfs/usr/{bin/tcc, lib/tcc/{libtcc1.a,include/*.h}}
# installed into the root disk by tools/build_x86_rootfs.sh together with the C headers and
# startup objects (the "development files": see that script).
#
# tcc's own ./configure is not run: it assumes the compiler it builds can be executed here.
# The two files it generates (config.mak, config.h) are written below instead, using the same
# settings it would for a cross build, and the helper that must run on the build machine
# (c2str) is built with the host compiler. libtcc1.a (the runtime tcc links into every program)
# is built here too, with the cross compiler, since the stock build would run the new tcc.
#   tools/build_x86_tcc.sh        # REBUILD=1 to start from a fresh tree
set -euo pipefail

REPO="$(cd "$(dirname "$0")/.." && pwd)"
UL="${EXTRON_USERLAND:-$REPO/build-x86_64/userland}"
B="$REPO/build-x86_64/tcc"
REV=32d1c0a5614b9979768b3711726db3d601750ed3
SHA=d67f3d27db088deafb4db4fdf82f4beddfdc08d784f159a5231628bfc6f19f04
TAR="$REPO/build-x86_64/extlibs/dl/tinycc-$REV.tar.gz"
JOBS="${JOBS:-$(nproc 2>/dev/null || echo 4)}"
export EXTRON_SYSROOT="$UL/sysroot"
CC="$REPO/tools/x86_64-extron-gcc"
[ -f "$EXTRON_SYSROOT/usr/lib/libc.so" ] || { echo "build the userland first" >&2; exit 1; }

mkdir -p "$B" "$(dirname "$TAR")"
[ -f "$TAR" ] || curl -fsSL "https://github.com/TinyCC/tinycc/archive/$REV.tar.gz" -o "$TAR"
echo "$SHA  $TAR" | sha256sum -c - >/dev/null
SRC="$B/tinycc-$REV"
if [ ! -d "$SRC" ] || [ "${REBUILD:-0}" = 1 ]; then
    rm -rf "$SRC"; tar -xzf "$TAR" -C "$B"
    python3 - "$SRC" <<'PY'
import sys
src = sys.argv[1]
# Extron is not Linux: the wrapper compiler undefines __linux__ and defines __extron__, and
# tcc must do the same (its predefines also pick Linux's type choices from __linux__, which
# Extron shares: 64-bit long, int wchar_t).
p = src + "/tccpp.c"; s = open(p).read()
old = '    "__linux__\\0"\n    "__linux\\0"\n'
assert old in s
open(p, "w").write(s.replace(old, '    "__extron__ 1\\0"\n', 1))
p = src + "/include/tccdefs.h"; s = open(p).read()
assert "defined __linux__" in s
open(p, "w").write(s.replace("defined __linux__", "defined __extron__"))
# GNU ld defines __ehdr_start (the ELF header's address); mlibc's static startup finds its own
# program headers through it. tcc places the headers at the image base of a non-PIE executable.
p = src + "/tccelf.c"; s = open(p).read()
old = '    set_linker_sym(s1, "_end", bss_section, 0);\n#if TARGETOS_OpenBSD'
assert old in s
new = ('    set_linker_sym(s1, "_end", bss_section, 0);\n'
       '    if (!(s1->output_type & TCC_OUTPUT_DYN))\n'
       '        set_global_sym(s1, "__ehdr_start", NULL, ELF_START_ADDR);\n'
       '#if TARGETOS_OpenBSD')
open(p, "w").write(s.replace(old, new, 1))
PY
    # mlibc's headers use GCC's predefined type and limit macros (__UINT8_TYPE__, __INTMAX_MAX__,
    # __SIZEOF_LONG__, ...). Extron is x86-64 LP64 exactly like the build machine, so take them
    # from GCC's own table and append them to tcc's built-in predefines.
    {
        # (indented: in tccdefs.h only indented lines become runtime predefines)
        echo "    /* GCC's type/limit macros, added by tools/build_x86_tcc.sh */"
        gcc -dM -E -x c /dev/null | grep -E '^#define __(U?INT(_LEAST|_FAST)?[0-9]+_(TYPE|MAX|WIDTH)__|U?INT(PTR|MAX)_(TYPE|MAX|WIDTH)__|SIZE_(TYPE|MAX|WIDTH)__|PTRDIFF_(TYPE|MAX|WIDTH)__|WCHAR_(TYPE|MAX|MIN|WIDTH)__|WINT_(TYPE|MAX|MIN|WIDTH)__|CHAR(16|32)_TYPE__|SIG_ATOMIC_(TYPE|MAX|MIN|WIDTH)__|SCHAR_(MAX|WIDTH)__|SHRT_(MAX|WIDTH)__|INT_(MAX|WIDTH)__|LONG_(MAX|WIDTH)__|LONG_LONG_(MAX|WIDTH)__|SIZEOF_[A-Z_0-9]+__|CHAR_BIT__|U?INT[0-9]*_C\(c\)|U?INTMAX_C\(c\))' \
            | grep -v -E '^#define __(SIZE_TYPE|PTRDIFF_TYPE|WCHAR_TYPE|WINT_TYPE|INT_MAX|LONG_MAX|LONG_LONG_MAX|CHAR_BIT|SIZEOF_INT|SIZEOF_LONG_LONG|INT64_TYPE|INTPTR_TYPE|UINTPTR_TYPE|SIZEOF_INT128|SIZEOF_FLOAT128|SIZEOF_FLOAT80|SIZEOF_FLOAT16|SIZEOF_FLOAT32|SIZEOF_FLOAT64|SIZEOF_FLOAT128X)__ ' || true
    } | sed -E '/^    \/\*/! s/^/    /' >> "$SRC/include/tccdefs.h"
fi

cd "$SRC"
VERSION="$(head VERSION)"
GCC_MAJOR="$(gcc -dumpversion | cut -d. -f1)"
cat > config.mak <<MK
# Generated by tools/build_x86_tcc.sh (what ./configure --cpu=x86_64 --targetos=Extron would write)
prefix=/usr
bindir=\$(DESTDIR)/usr/bin
tccdir=\$(DESTDIR)/usr/lib/tcc
libdir=\$(DESTDIR)/usr/lib
includedir=\$(DESTDIR)/usr/include
mandir=\$(DESTDIR)/usr/share/man
infodir=\$(DESTDIR)/usr/share/info
docdir=\$(DESTDIR)/usr/share/doc
CC=$CC
CC_NAME=gcc
GCC_MAJOR=$GCC_MAJOR
GCC_MINOR=0
AR=ar
LIBSUF=.a
EXESUF=
DLLSUF=.so
CFLAGS=-O2 -std=gnu17 -w
LDFLAGS=
ARCH=x86_64
TARGETOS=Extron
BUILDOS=Linux
VERSION=$VERSION
TOPSRC=\$(TOP)
CONFIG_x86_64=yes
CONFIG_bcheck=no
CONFIG_backtrace=no
MK
cat > config.h <<H
/* Generated by tools/build_x86_tcc.sh */
#define TCC_VERSION "$VERSION"
#define CC_NAME CC_gcc
#define GCC_MAJOR $GCC_MAJOR
#define GCC_MINOR 0
#if !(TCC_TARGET_I386 || TCC_TARGET_X86_64 || TCC_TARGET_ARM\\
 || TCC_TARGET_ARM64 || TCC_TARGET_RISCV64 || TCC_TARGET_C67)
#define TCC_TARGET_X86_64 1
#define CONFIG_TCC_BCHECK 0
#define CONFIG_TCC_BACKTRACE 0
#define CONFIG_TCC_SYSINCLUDEPATHS "{B}/include:/usr/include"
#define CONFIG_TCC_LIBPATHS "{B}:/usr/lib"
#define CONFIG_TCC_CRTPREFIX "/usr/lib"
#define CONFIG_TCC_ELFINTERP "/lib/ld.so"
#endif

#ifndef CONFIG_TCCDIR
#define CONFIG_TCCDIR "/usr/lib/tcc"
#endif
#define CONFIG_TCC_PREDEFS 1
H

# Host helper first (it runs here), then the compiler itself with the cross compiler.
rm -f c2str.exe tccdefs_.h
gcc -DC2STR conftest.c -o c2str.exe
./c2str.exe include/tccdefs.h tccdefs_.h
make -j"$JOBS" tcc >"$B/make.log" 2>&1 || { grep -E "error|Error" "$B/make.log" | head -20; exit 1; }

# libtcc1.a: the runtime library every tcc program links (compiler helpers, alloca, va_list,
# atomics, dso handle), built with the cross compiler.
LIBDIR="$B/libtcc1"; rm -rf "$LIBDIR"; mkdir -p "$LIBDIR"
for f in libtcc1.c stdatomic.c builtin.c va_list.c dsohandle.c; do
    "$CC" -O2 -w -fPIC -fno-omit-frame-pointer -I"$SRC" -c "lib/$f" -o "$LIBDIR/${f%.c}.o"
done
for f in atomic.S alloca.S; do
    "$CC" -O2 -w -I"$SRC" -c "lib/$f" -o "$LIBDIR/${f%.S}.o"
done
rm -f "$B/libtcc1.a"; ar rcs "$B/libtcc1.a" "$LIBDIR"/*.o

R="$B/rootfs/usr"; rm -rf "$B/rootfs"; mkdir -p "$R/bin" "$R/lib/tcc/include"
install -m 755 tcc "$R/bin/tcc"
strip --strip-unneeded "$R/bin/tcc" 2>/dev/null || true
install -m 644 "$B/libtcc1.a" "$R/lib/tcc/libtcc1.a"
for h in include/*.h; do case "$h" in */tccdefs.h) ;; *) install -m 644 "$h" "$R/lib/tcc/include/";; esac; done
# The compiler's own source, configured to be rebuilt ON Extron with the system cc: the cross
# build above is only the bootstrap. /usr/src/tcc-extron-src.tar.gz on the root disk.
G="$B/guest"; rm -rf "$G"; mkdir -p "$G" "$R/src"
tar -C "$B" --exclude='*.o' --exclude=tcc --exclude=c2str.exe --exclude=libtcc.a --exclude=tccdefs_.h \
    -cf - "tinycc-$REV" | tar -C "$G" -xf -
sed -i 's|^CC=.*|CC=cc|; s|^CC_NAME=.*|CC_NAME=tcc|; s|^AR=.*|AR=ar|; s|^CFLAGS=.*|CFLAGS=-O2 -w|' "$G/tinycc-$REV/config.mak"
tar -C "$G" -czf "$R/src/tcc-extron-src.tar.gz" "tinycc-$REV"

echo "tcc $VERSION: $(stat -c %s "$R/bin/tcc") bytes, libtcc1.a $(stat -c %s "$R/lib/tcc/libtcc1.a") bytes"
